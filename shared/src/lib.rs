//! shared — common types used across all services
//!
//! This crate is the single source of truth for data structures that are
//! shared between rust-collector, real-trader, and vps-api.
//!
//! When building core-node, all services import from here instead of
//! duplicating struct definitions.

use serde::{Deserialize, Serialize};

// ─── Market data ──────────────────────────────────────────────────────────────

/// Best bid/ask, mid-price, 24h volume (USD) and current funding rate for a
/// single perpetual contract on one exchange.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct TickerData {
    pub bid: f64,
    pub ask: f64,
    pub price: f64,
    pub vol: f64,
    #[serde(rename = "fundingRate", default)]
    pub funding_rate: f64,
    /// Volume (in base asset units) available at the best bid level.
    #[serde(skip)]
    pub bid_size: f64,
    /// Volume (in base asset units) available at the best ask level.
    #[serde(skip)]
    pub ask_size: f64,
    /// Unix seconds of last WebSocket update (set by collector, not serialised).
    #[serde(skip)]
    pub last_updated: u64,
}

/// One spread opportunity: a single pair available on two exchanges where the
/// price diverges enough to be interesting.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SpreadRow {
    pub pair: String,
    #[serde(rename = "exchangeA")]
    pub exchange_a: String,
    #[serde(rename = "exchangeB")]
    pub exchange_b: String,
    #[serde(rename = "priceA")]
    pub price_a: f64,
    #[serde(rename = "priceB")]
    pub price_b: f64,
    #[serde(rename = "bidA")]
    pub bid_a: f64,
    #[serde(rename = "askA")]
    pub ask_a: f64,
    #[serde(rename = "bidB")]
    pub bid_b: f64,
    #[serde(rename = "askB")]
    pub ask_b: f64,
    #[serde(rename = "volA", default)]
    pub vol_a: f64,
    #[serde(rename = "volB", default)]
    pub vol_b: f64,
    #[serde(rename = "fundingA", default)]
    pub funding_a: f64,
    #[serde(rename = "fundingB", default)]
    pub funding_b: f64,
    /// Structural mean spread over the last 24h (Time-decay EMA).
    pub structural_spread: f64,
    /// Maximum observed spread since tracking began (all-time high for this pair/direction).
    pub structural_max: f64,
    /// Minimum observed spread since tracking began (all-time low for this pair/direction).
    pub structural_min: f64,
    /// Spread in percent (positive = buy B / sell A is profitable before costs).
    pub spread: f64,
    /// E.g. "gate>kucoin" — the exchange with the higher bid comes first.
    pub direction: String,
    #[serde(default)]
    pub has_structural_spread: bool,
    /// Whether the structural spread has been verified from historical data.
    /// false = pair is still "checking", entry should be blocked.
    #[serde(default)]
    pub structural_verified: bool,
}

/// A fully calculated execution signal generated by the scanner.
/// Given to the engine for immediate execution with zero token analysis.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TradeSignal {
    pub profile_id: String,
    pub pair: String,
    pub exchange_a: String,
    pub exchange_b: String,
    pub direction: String,

    // Pre-calculated target physics for execution
    pub contracts_a: f64,
    pub contracts_b: f64,
    pub target_qty_a: f64, // Physical volume taking multiplier into account (for Binance/Bybit)
    pub target_qty_b: f64,
    pub limit_price_a: f64,
    pub limit_price_b: f64,

    // Core validation metrics
    pub entry_a: f64,
    pub entry_b: f64,
    pub actual_vol_a_usd: f64,
    pub actual_vol_b_usd: f64,
    pub break_even_pct: f64,
    pub spread: f64,
    pub structural_spread: f64,
    pub is_a_higher: bool,

    // Base math contexts (in case emergency closes or logging needs them)
    pub tick_a: f64,
    pub tick_b: f64,
    pub mult_a: f64,
    pub mult_b: f64,
}

/// Payload sent from rust-collector to traders via HTTP POST /internal/spreads.
/// In core-node, this is replaced by a direct in-memory reference to the
/// PriceMap (Arc<DashMap>), but the HTTP form is preserved for compatibility.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SpreadPayload {
    pub spreads: Vec<SpreadRow>,
    /// Full ticker snapshot: exchange → symbol → TickerData.
    pub maps: std::collections::HashMap<String, std::collections::HashMap<String, TickerData>>,
}

